// Expo config plugin — Android network security posture (fixes the cleartext blocker).
//
// PREVIOUS BEHAVIOR (removed): this plugin forced
// android:usesCleartextTraffic="true" on the MAIN manifest, so EVERY variant
// — including release/store builds — permitted plain http://. That is a
// production security hole (MITM, token/credential theft, payment tampering).
//
// NEW BEHAVIOR (secure by default):
//   • Release builds BLOCK cleartext. We set usesCleartextTraffic="false" on
//     the application and install a res/xml network security config whose
//     base-config sets cleartextTrafficPermitted="false". HTTPS is required.
//   • Debug builds keep working over http on the LAN: Expo's template already
//     sets usesCleartextTraffic="true" in the DEBUG manifest only, and the
//     network security config permits cleartext solely inside a
//     <debug-overrides> block (which Android ignores for release builds).
//   • Certificate / public-key PINNING is wired but not fabricated: set
//     EXPO_PUBLIC_API_PIN (and optional EXPO_PUBLIC_API_PIN_BACKUP + the host
//     via EXPO_PUBLIC_API_PIN_DOMAIN) at prebuild time and the config adds a
//     <pin-set> with a backup pin. Real pin values are deployment-specific
//     (they are the SPKI SHA-256 of YOUR server's cert chain) — compute them
//     with the command in mobile/SECURITY.md and set the env; nothing is
//     hardcoded or guessed here.
//   • Escape hatch for a controlled http pilot ONLY: set
//     EXPO_PUBLIC_ALLOW_CLEARTEXT="true" at prebuild to re-permit cleartext in
//     a release build. It is OFF by default and must never be set for a store
//     build.
//
// Zero new dependencies: @expo/config-plugins ships inside the expo package.
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require("@expo/config-plugins");
const fs = require("fs");
const path = require("path");

const ALLOW_CLEARTEXT = process.env.EXPO_PUBLIC_ALLOW_CLEARTEXT === "true";
const PIN = (process.env.EXPO_PUBLIC_API_PIN || "").trim();
const PIN_BACKUP = (process.env.EXPO_PUBLIC_API_PIN_BACKUP || "").trim();
const PIN_DOMAIN = (process.env.EXPO_PUBLIC_API_PIN_DOMAIN || "").trim();

function buildNetworkSecurityConfigXml() {
  const pinBlock =
    PIN && PIN_DOMAIN
      ? `
  <!-- Certificate/public-key pinning for the production API host. Pins are
       SPKI SHA-256 digests supplied via EXPO_PUBLIC_API_PIN(_BACKUP) at build
       time; a backup pin is required so a planned cert rotation can't brick
       the app. -->
  <domain-config cleartextTrafficPermitted="false">
    <domain includeSubdomains="true">${PIN_DOMAIN}</domain>
    <pin-set>
      <pin digest="SHA-256">${PIN}</pin>${
          PIN_BACKUP ? `\n      <pin digest="SHA-256">${PIN_BACKUP}</pin>` : ""
        }
    </pin-set>
  </domain-config>`
      : "";

  // Base: cleartext OFF everywhere. Debug builds may talk http to the LAN via
  // the debug-overrides block, which Android applies ONLY to debuggable builds
  // — release/store builds ignore it entirely.
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-cleartext-http.js. Do not edit by hand. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="${ALLOW_CLEARTEXT ? "true" : "false"}">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>${pinBlock}
  <debug-overrides>
    <trust-anchors>
      <certificates src="system" />
      <certificates src="user" />
    </trust-anchors>
  </debug-overrides>
</network-security-config>
`;
}

module.exports = function withAndroidNetworkSecurity(config) {
  // 1) Write res/xml/network_security_config.xml.
  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const resXmlDir = path.join(
        cfg.modRequest.platformProjectRoot,
        "app",
        "src",
        "main",
        "res",
        "xml"
      );
      fs.mkdirSync(resXmlDir, { recursive: true });
      fs.writeFileSync(
        path.join(resXmlDir, "network_security_config.xml"),
        buildNetworkSecurityConfigXml(),
        "utf8"
      );
      return cfg;
    },
  ]);

  // 2) Point the manifest at it and set the cleartext flag (false unless the
  //    explicit pilot opt-in is present).
  config = withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$["android:networkSecurityConfig"] = "@xml/network_security_config";
    app.$["android:usesCleartextTraffic"] = ALLOW_CLEARTEXT ? "true" : "false";
    return cfg;
  });

  return config;
};

// Exported for unit testing (not part of the Expo plugin contract).
module.exports._buildNetworkSecurityConfigXml = buildNetworkSecurityConfigXml;
